// Бинауральные ритмы для мозга. В наушниках в левое и правое ухо подаются две
// близкие частоты; мозг воспринимает их разницу как ритм (биение).
// Значения традиционные/ознакомительные, не являются медицинской рекомендацией.

export const BINAURAL = [
  { id: 'delta', hz: 3, title: 'Дельта', label: 'Глубокий сон', color: '#5B7CFA', desc: '0,5–4 Гц. Глубокий сон и восстановление, выработка гормона роста.' },
  { id: 'theta', hz: 6, title: 'Тета', label: 'Медитация', color: '#8B8CF8', desc: '4–8 Гц. Расслабление, креативность, работа с подсознанием и установками.' },
  { id: 'alpha', hz: 10, title: 'Альфа', label: 'Спокойный фокус', color: '#34D1BF', desc: '8–13 Гц. Спокойная ясность, снижение тревожности, лёгкая медитация.' },
  { id: 'beta', hz: 18, title: 'Бета', label: 'Концентрация', color: '#FFC24B', desc: '13–30 Гц. Активное бодрствование, внимание и решение задач.' },
  { id: 'gamma', hz: 40, title: 'Гамма', label: 'Инсайты', color: '#FF8A65', desc: '30–40 Гц. Высокая когнитивная активность, озарения и собранность.' },
];

export function binauralByHz(hz) {
  return BINAURAL.find((b) => b.hz === hz) || BINAURAL.find((b) => b.id === 'alpha');
}
