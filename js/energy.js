export function energyProgramById(id) {
  const p = ENERGY_PRESETS.find((x) => x.id === id) || ENERGY_PRESETS[1];
  return {
    presetId: p.id, presetTitle: p.title, title: 'Энергодыхание',
    totalSeconds: p.stages.reduce((s, x) => s + x.seconds, 0),
    stages: p.stages,
  };
}

